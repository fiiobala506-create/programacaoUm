public class Ex5 {

	public static void main(String[] args) {
		
        double arroz = 27.90;
        double feijao = 9.80;
        double oleo = 8.50;

        double total = arroz + feijao + oleo;
        double media = total / 3;
        
        System.out.println("Valor do arroz: R$ " + arroz);
        System.out.println("Valor do feijão: R$ " + feijao);
        System.out.println("Valor do óleo: R$ " + oleo);
        System.out.println("Valor total da compra: R$ " + total);
        System.out.println("Valor médio dos produtos: R$ " + media);

	}

}
